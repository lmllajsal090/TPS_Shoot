static FString Write(const TSharedRef<FJsonObject>& Object)
{
    FString Text;
    FJsonSerializer::Serialize(Object, TJsonWriterFactory<>::Create(&Text));
    return Text;
}
static FString LayoutError(const FString& Message)
{
    auto J=MakeShared<FJsonObject>(); J->SetBoolField(TEXT("ok"),false); J->SetStringField(TEXT("error"),Message); return Write(J);
}
static UEdGraph* Resolve(UBlueprint* BP,const FString& Name)
{
    if (!BP || !GEditor || GEditor->PlayWorld) return nullptr;
    TArray<UEdGraph*> Graphs; BP->GetAllGraphs(Graphs);
    UEdGraph* Found=nullptr;
    for (UEdGraph* Graph:Graphs)
        if (Graph && (Graph->GetName()==Name || Graph->GetPathName()==Name))
        { if (Found) return nullptr; Found=Graph; }
    return Found;
}
static SGraphEditor* FindWidget(const TSharedRef<SWidget>& Widget,UEdGraph* Graph)
{
    if (Widget->GetType()==FName(TEXT("SGraphEditor")))
    {
        auto* Candidate=static_cast<SGraphEditor*>(&Widget.Get());
        if (Candidate->GetCurrentGraph()==Graph) return Candidate;
    }
    FChildren* Children=Widget->GetChildren();
    if (Children) for (int32 I=0;I<Children->Num();++I)
        if (auto* Found=FindWidget(Children->GetChildAt(I),Graph)) return Found;
    return nullptr;
}
static SGraphEditor* FindEditor(UEdGraph* Graph)
{
    if (!FSlateApplication::IsInitialized()) return nullptr;
    TFunction<SGraphEditor*(const TSharedRef<SWindow>&)> SearchWindow;
    SearchWindow=[&](const TSharedRef<SWindow>& Window)->SGraphEditor*
    {
        if (auto* Found=FindWidget(Window,Graph)) return Found;
        for (const auto& Child:Window->GetChildWindows()) if (auto* Found=SearchWindow(Child)) return Found;
        return nullptr;
    };
    for (const auto& Window:FSlateApplication::Get().GetTopLevelWindows())
        if (auto* Found=SearchWindow(Window)) return Found;
    return nullptr;
}
static FString Guid(UEdGraphNode* Node) { return Node->NodeGuid.ToString(); }
static FString PinSemantics(const UEdGraphPin* Pin)
{
    // Tooltips/friendly labels are populated lazily by Slate hover. They are UI caches,
    // not graph logic. Keep all functional pin data without those volatile strings.
    auto J=MakeShared<FJsonObject>();
    FString TypeText; FEdGraphPinType::StaticStruct()->ExportText(TypeText,&Pin->PinType,nullptr,nullptr,PPF_None,nullptr);
    FString TextDefault; FTextStringHelper::WriteToBuffer(TextDefault,Pin->DefaultTextValue);
    J->SetStringField(TEXT("type"),TypeText); J->SetStringField(TEXT("name"),Pin->PinName.ToString());
    J->SetNumberField(TEXT("direction"),int32(Pin->Direction)); J->SetNumberField(TEXT("source_index"),Pin->SourceIndex);
    J->SetStringField(TEXT("default"),Pin->DefaultValue); J->SetStringField(TEXT("autogenerated_default"),Pin->AutogeneratedDefaultValue);
    J->SetStringField(TEXT("default_object"),GetPathNameSafe(Pin->DefaultObject)); J->SetStringField(TEXT("default_text"),TextDefault);
    J->SetStringField(TEXT("persistent_guid"),Pin->PersistentGuid.ToString());
    auto Ref=[](const UEdGraphPin* P)->FString { return P ? Guid(P->GetOwningNode())+TEXT(":")+P->PinId.ToString() : FString(); };
    J->SetStringField(TEXT("parent_pin"),Ref(Pin->ParentPin)); J->SetStringField(TEXT("reference_pass_through"),Ref(Pin->ReferencePassThroughConnection));
    TArray<FString> Links; for (const auto* P:Pin->LinkedTo) if (P) Links.Add(Ref(P)); Links.Sort();
    J->SetStringField(TEXT("links"),FString::Join(Links,TEXT("|")));
    TArray<FString> Children; for (const auto* P:Pin->SubPins) Children.Add(Ref(P));
    J->SetStringField(TEXT("sub_pins"),FString::Join(Children,TEXT("|")));
    J->SetBoolField(TEXT("hidden"),Pin->bHidden); J->SetBoolField(TEXT("not_connectable"),Pin->bNotConnectable);
    J->SetBoolField(TEXT("default_read_only"),Pin->bDefaultValueIsReadOnly); J->SetBoolField(TEXT("default_ignored"),Pin->bDefaultValueIsIgnored);
    J->SetBoolField(TEXT("advanced"),Pin->bAdvancedView); J->SetBoolField(TEXT("orphaned"),Pin->bOrphanedPin);
    J->SetBoolField(TEXT("backwards_compat_empty"),Pin->bUseBackwardsCompatForEmptyAutogeneratedValue);
    return Write(J);
}
static FString Semantics(UEdGraph* Graph)
{
    // Include every non-transient reflected node property and functional native pin data.
    // Only editor layout fields are excluded. Sorting removes UObject/container iteration order.
    TArray<FString> Lines;
    for (UEdGraphNode* Node:Graph->Nodes)
    {
        if (!Node) continue;
        const FString Key=Guid(Node);
        Lines.Add(Key+TEXT("|class|")+Node->GetClass()->GetPathName());
        for (TFieldIterator<FProperty> It(Node->GetClass());It;++It)
        {
            FProperty* Property=*It;
            const FString Name=Property->GetName();
            if (Property->HasAnyPropertyFlags(CPF_Transient|CPF_DuplicateTransient|CPF_NonPIEDuplicateTransient) ||
                Name==TEXT("NodePosX") || Name==TEXT("NodePosY") || Name==TEXT("NodeWidth") || Name==TEXT("NodeHeight")) continue;
            FString Value; Property->ExportText_InContainer(0,Value,Node,Node,Node,PPF_None);
            Lines.Add(Key+TEXT("|property|")+Name+TEXT("|")+Value);
        }
        for (const UEdGraphPin* Pin:Node->Pins) if (Pin)
        {
            const FString Value=PinSemantics(Pin);
            Lines.Add(Key+TEXT("|pin|")+Pin->PinId.ToString()+TEXT("|")+Value);
        }
    }
    Lines.Sort(); return FString::Join(Lines,TEXT("\n"));
}
static TSharedRef<FJsonObject> NodeJson(UEdGraphNode* Node,SGraphEditor* Editor)
{
    auto J=MakeShared<FJsonObject>();
    J->SetStringField(TEXT("guid"),Guid(Node)); J->SetStringField(TEXT("name"),Node->GetName());
    J->SetStringField(TEXT("title"),Node->GetNodeTitle(ENodeTitleType::ListView).ToString());
    J->SetStringField(TEXT("class"),Node->GetClass()->GetPathName());
    J->SetBoolField(TEXT("comment"),Node->IsA<UEdGraphNode_Comment>());
    J->SetNumberField(TEXT("x"),Node->NodePosX); J->SetNumberField(TEXT("y"),Node->NodePosY);
    J->SetNumberField(TEXT("stored_width"),Node->NodeWidth); J->SetNumberField(TEXT("stored_height"),Node->NodeHeight);
    FVector2D Size=FVector2D::ZeroVector;
    if (Editor) if (auto Widget=Editor->GetGraphPanel()->GetNodeWidgetFromGuid(Node->NodeGuid)) Size=FVector2D(Widget->GetDesiredSize());
    J->SetNumberField(TEXT("width"),Size.X); J->SetNumberField(TEXT("height"),Size.Y);
    TArray<TSharedPtr<FJsonValue>> Pins;
    for (const UEdGraphPin* Pin:Node->Pins) if (Pin)
    {
        auto P=MakeShared<FJsonObject>(); P->SetStringField(TEXT("id"),Pin->PinId.ToString());
        P->SetStringField(TEXT("name"),Pin->PinName.ToString()); P->SetBoolField(TEXT("output"),Pin->Direction==EGPD_Output);
        P->SetStringField(TEXT("category"),Pin->PinType.PinCategory.ToString());
        P->SetStringField(TEXT("default"),Pin->DefaultValue);
        TArray<TSharedPtr<FJsonValue>> Links;
        for (const UEdGraphPin* Link:Pin->LinkedTo) if (Link) Links.Add(MakeShared<FJsonValueString>(Guid(Link->GetOwningNode())+TEXT(":")+Link->PinId.ToString()));
        P->SetArrayField(TEXT("links"),Links); Pins.Add(MakeShared<FJsonValueObject>(P));
    }
    J->SetArrayField(TEXT("pins"),Pins); return J;
}
static TSharedRef<FJsonObject> Inspect(UEdGraph* Graph,SGraphEditor* Editor)
{
    auto J=MakeShared<FJsonObject>(); J->SetBoolField(TEXT("ok"),true);
    J->SetStringField(TEXT("graph"),Graph->GetPathName()); J->SetStringField(TEXT("semantics"),Semantics(Graph));
    TArray<TSharedPtr<FJsonValue>> Nodes;
    for (UEdGraphNode* Node:Graph->Nodes) if (Node) Nodes.Add(MakeShared<FJsonValueObject>(NodeJson(Node,Editor)));
    J->SetArrayField(TEXT("nodes"),Nodes); return J;
}
