FString UBlueprintLayoutAutomationLibrary::PrepareGraph(UBlueprint* Blueprint,const FString& GraphName)
{
    UEdGraph* Graph=Resolve(Blueprint,GraphName); if (!Graph) return LayoutError(TEXT("Graph missing/ambiguous, invalid Blueprint, or PIE active."));
    GEditor->GetEditorSubsystem<UAssetEditorSubsystem>()->OpenEditorForAsset(Blueprint);
    FKismetEditorUtilities::BringKismetToFocusAttentionOnObject(Graph);
    if (auto* Editor=FindEditor(Graph))
        if (auto Window=FSlateApplication::Get().FindWidgetWindow(Editor->AsShared())) Window->ShowWindow();
    auto J=MakeShared<FJsonObject>(); J->SetBoolField(TEXT("ok"),true); J->SetStringField(TEXT("graph"),Graph->GetPathName());
    J->SetStringField(TEXT("next"),TEXT("Wait for a Slate tick, then inspect/plan; do not combine prepare and plan in one call.")); return Write(J);
}
FString UBlueprintLayoutAutomationLibrary::InspectGraph(UBlueprint* Blueprint,const FString& GraphName)
{
    UEdGraph* Graph=Resolve(Blueprint,GraphName); if (!Graph) return LayoutError(TEXT("Graph missing/ambiguous, invalid Blueprint, or PIE active."));
    return Write(Inspect(Graph,FindEditor(Graph)));
}
FString UBlueprintLayoutAutomationLibrary::PlanLayout(UBlueprint* Blueprint,const FString& GraphName,const TArray<FString>& NodeGuids)
{
    UEdGraph* Graph=Resolve(Blueprint,GraphName); if (!Graph) return LayoutError(TEXT("Graph missing/ambiguous, invalid Blueprint, or PIE active."));
    if (!Graph->GetSchema() || Graph->GetSchema()->GetClass()->GetName()!=TEXT("EdGraphSchema_K2")) return LayoutError(TEXT("This adapter is validated for K2 event/function graphs only."));
    SGraphEditor* Editor=FindEditor(Graph); if (!Editor) return LayoutError(TEXT("Prepare the named graph and wait for Slate before planning."));
    TSet<UEdGraphNode*> Scope;
    for (UEdGraphNode* Node:Graph->Nodes) if (Node && (NodeGuids.IsEmpty() || NodeGuids.Contains(Guid(Node)))) Scope.Add(Node);
    if (Scope.IsEmpty() || (!NodeGuids.IsEmpty() && Scope.Num()!=TSet<FString>(NodeGuids).Num())) return LayoutError(TEXT("Empty scope or unknown/duplicate node GUID."));
    auto& Formatter=FFormatter::Instance(); Formatter.SetCurrentEditor(Editor,Blueprint);
    for (UEdGraphNode* Node:Graph->Nodes) if (Node && !Formatter.GetWidget(Node)) return LayoutError(TEXT("Slate node widgets not ready; allow another tick."));
    if (!Formatter.PreCommand()) return LayoutError(TEXT("Formatter could not prepare the graph."));
    TSharedRef<FJsonObject> Before=Inspect(Graph,Editor);
    TUniquePtr<FFormatterGraph> Layout(UEGraphAdapter::Build(Scope,false)); Layout->Format();
    auto Bounds=Layout->GetBoundMap(); Formatter.PostCommand();
    FVector2D OldMin(TNumericLimits<double>::Max(),TNumericLimits<double>::Max()),NewMin=OldMin;
    for (auto* Node:Scope) { OldMin.X=FMath::Min(OldMin.X,double(Node->NodePosX)); OldMin.Y=FMath::Min(OldMin.Y,double(Node->NodePosY)); }
    for (const auto& Item:Bounds) { NewMin.X=FMath::Min(NewMin.X,Item.Value.Min.X); NewMin.Y=FMath::Min(NewMin.Y,Item.Value.Min.Y); }
    TArray<TSharedPtr<FJsonValue>> Positions;
    for (const auto& Item:Bounds)
    {
        auto* Node=static_cast<UEdGraphNode*>(Item.Key);
        if (!Scope.Contains(Node)) return LayoutError(TEXT("Formatter returned a node outside the explicitly requested scope."));
        auto J=NodeJson(Node,Editor); J->SetNumberField(TEXT("x"),FMath::RoundToInt(Item.Value.Min.X+OldMin.X-NewMin.X));
        J->SetNumberField(TEXT("y"),FMath::RoundToInt(Item.Value.Min.Y+OldMin.Y-NewMin.Y));
        J->SetNumberField(TEXT("width"),Item.Value.GetSize().X); J->SetNumberField(TEXT("height"),Item.Value.GetSize().Y);
        Positions.Add(MakeShared<FJsonValueObject>(J));
    }
    auto J=MakeShared<FJsonObject>(); J->SetBoolField(TEXT("ok"),true); J->SetStringField(TEXT("backend"),TEXT("GraphFormatter 2.3.1 c144d9f"));
    J->SetStringField(TEXT("graph"),Graph->GetPathName()); J->SetObjectField(TEXT("before"),Before); J->SetArrayField(TEXT("positions"),Positions); return Write(J);
}
FString UBlueprintLayoutAutomationLibrary::ApplyLayout(UBlueprint* Blueprint,const FString& GraphName,const FString& PlanJson)
{
    UEdGraph* Graph=Resolve(Blueprint,GraphName); if (!Graph) return LayoutError(TEXT("Graph missing/ambiguous, invalid Blueprint, or PIE active."));
    TSharedPtr<FJsonObject> Plan; if (!FJsonSerializer::Deserialize(TJsonReaderFactory<>::Create(PlanJson),Plan) || !Plan) return LayoutError(TEXT("Invalid plan JSON."));
    FString Target; const TSharedPtr<FJsonObject>* Before=nullptr; const TArray<TSharedPtr<FJsonValue>>* Positions=nullptr;
    if (!Plan->TryGetStringField(TEXT("graph"),Target) || Target!=Graph->GetPathName() || !Plan->TryGetObjectField(TEXT("before"),Before) || !Plan->TryGetArrayField(TEXT("positions"),Positions)) return LayoutError(TEXT("Plan target or required fields invalid."));
    FString Expected; if (!(*Before)->TryGetStringField(TEXT("semantics"),Expected) || Expected!=Semantics(Graph)) return LayoutError(TEXT("STALE_PLAN: graph properties or connections changed."));
    TMap<FString,UEdGraphNode*> Nodes;
    for (UEdGraphNode* Node:Graph->Nodes) if (Node) Nodes.Add(Guid(Node),Node);
    for (const auto& Value:(*Before)->GetArrayField(TEXT("nodes")))
    {
        auto J=Value->AsObject(); auto* Node=Nodes.FindRef(J->GetStringField(TEXT("guid")));
        if (!Node || Node->NodePosX!=J->GetIntegerField(TEXT("x")) || Node->NodePosY!=J->GetIntegerField(TEXT("y")) || Node->NodeWidth!=J->GetIntegerField(TEXT("stored_width")) || Node->NodeHeight!=J->GetIntegerField(TEXT("stored_height"))) return LayoutError(TEXT("STALE_PLAN: graph layout changed."));
    }
    TSet<FString> Seen;
    for (const auto& Value:*Positions)
    {
        auto J=Value->AsObject(); if (!J) return LayoutError(TEXT("Invalid layout node."));
        FString Id; double X,Y,W,H;
        if (!J->TryGetStringField(TEXT("guid"),Id) || !Nodes.Contains(Id) || Seen.Contains(Id) || !J->TryGetNumberField(TEXT("x"),X) || !J->TryGetNumberField(TEXT("y"),Y) || !J->TryGetNumberField(TEXT("width"),W) || !J->TryGetNumberField(TEXT("height"),H) || !FMath::IsFinite(X) || !FMath::IsFinite(Y) || !FMath::IsFinite(W) || !FMath::IsFinite(H) || FMath::Abs(X)>1e7 || FMath::Abs(Y)>1e7 || W<=0 || H<=0) return LayoutError(TEXT("Invalid coordinates, sizes, or duplicate node."));
        Seen.Add(Id);
    }
    if (Positions->IsEmpty()) return LayoutError(TEXT("Empty plan."));
    FScopedTransaction Transaction(NSLOCTEXT("GraphFormatterAutomation","ApplyLayout","Format named Blueprint graph (verified layout only)"));
    Blueprint->Modify(); Graph->Modify();
    for (const auto& Value:*Positions)
    {
        auto J=Value->AsObject(); auto* Node=Nodes[J->GetStringField(TEXT("guid"))]; Node->Modify();
        Node->NodePosX=J->GetIntegerField(TEXT("x")); Node->NodePosY=J->GetIntegerField(TEXT("y"));
        if (auto* Comment=Cast<UEdGraphNode_Comment>(Node)) Comment->SetBounds(FSlateRect(Node->NodePosX,Node->NodePosY,Node->NodePosX+J->GetNumberField(TEXT("width")),Node->NodePosY+J->GetNumberField(TEXT("height"))));
    }
    Graph->NotifyGraphChanged(); FBlueprintEditorUtils::MarkBlueprintAsModified(Blueprint);
    const bool Equal=Expected==Semantics(Graph);
    auto J=Inspect(Graph,FindEditor(Graph)); J->SetBoolField(TEXT("semantic_equal"),Equal); J->SetBoolField(TEXT("ok"),Equal); J->SetBoolField(TEXT("saved"),false); return Write(J);
}
FString UBlueprintLayoutAutomationLibrary::CaptureGraph(UBlueprint* Blueprint,const FString& GraphName,const FString& Filename,bool FitAll)
{
    UEdGraph* Graph=Resolve(Blueprint,GraphName); if (!Graph) return LayoutError(TEXT("Graph missing/ambiguous, invalid Blueprint, or PIE active."));
    SGraphEditor* Editor=FindEditor(Graph); if (!Editor) return LayoutError(TEXT("Graph editor not ready."));
    if (FitAll) { Editor->ZoomToFit(false); auto J=MakeShared<FJsonObject>(); J->SetBoolField(TEXT("ok"),true); J->SetBoolField(TEXT("captured"),false); J->SetStringField(TEXT("next"),TEXT("Wait for viewport animation, then capture with FitAll=false.")); return Write(J); }
    if (FPaths::GetExtension(Filename).ToLower()!=TEXT("png") || FPaths::IsRelative(Filename)) return LayoutError(TEXT("Use an absolute .png output path."));
    TArray<FColor> Pixels; FIntVector Size;
    if (!FSlateApplication::Get().TakeScreenshot(Editor->AsShared(),Pixels,Size)) return LayoutError(TEXT("Slate screenshot failed."));
    TArray64<uint8> PNG; FImageUtils::PNGCompressImageArray(Size.X,Size.Y,Pixels,PNG);
    if (!FFileHelper::SaveArrayToFile(PNG,*Filename)) return LayoutError(TEXT("PNG write failed."));
    auto J=MakeShared<FJsonObject>(); J->SetBoolField(TEXT("ok"),true); J->SetBoolField(TEXT("captured"),true); J->SetNumberField(TEXT("width"),Size.X); J->SetNumberField(TEXT("height"),Size.Y); J->SetStringField(TEXT("file"),Filename); return Write(J);
}
